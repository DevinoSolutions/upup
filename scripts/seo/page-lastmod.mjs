#!/usr/bin/env node
// Per-page last-modified snapshot for the landing sitemap (T-5788).
//
//   node scripts/seo/page-lastmod.mjs          # regenerate the snapshot from git
//   node scripts/seo/page-lastmod.mjs --check  # verify the committed snapshot
//
// The sitemap used to stamp ONE build-time `new Date()` on every URL, which
// told Google every page changed on every deploy (Google's response to a
// lastmod it cannot corroborate is to ignore the field site-wide), so the field
// was then dropped altogether. With no lastmod, the daily IndexNow workflow
// (scripts/ci/indexnow-submit.mjs) resubmits every URL every day. The honest
// value is "the last commit that touched what this page renders", and that has
// to come from git. The landing image builds without a .git directory
// (.dockerignore excludes it), so the build cannot ask git itself. Hence a
// COMMITTED snapshot, apps/landing/src/generated/page-lastmod.json, read by
// apps/landing/src/lib/page-lastmod.ts:
//
//   - REGENERATED by the husky pre-commit hook on every commit (by hand:
//     `pnpm run seo:lastmod`). A page whose sources are dirty or untracked at
//     that moment is stamped with today's UTC date: the commit being made IS
//     its last modification, and it is not in history yet.
//   - CHECKED in CI and in the same hook (`pnpm run seo:lastmod:check`): every
//     sitemapped page has an entry, no entry is orphaned, every date is a real
//     past-or-today date, every mapped source path exists, and (when the
//     checkout has history, not a shallow clone where `git log` would blame
//     the one fetched commit for everything) no entry is more than one day
//     older than what git says now.
//
// Ported from DoDomain's scripts/seo/page-lastmod.mjs. Plain Node with no
// dependencies, because CI runs Node 20 (no TypeScript stripping): the route
// ids the sitemap expands (FRAMEWORK_IDS, AGENT_IDS) are read from their .ts
// modules as TEXT, and the parse throws rather than return nothing. The vitest
// suite (apps/landing/src/__tests__/seo-surfaces.test.ts) cross-checks the
// snapshot's keys against the REAL sitemap() output, so a parse that drifts
// from what Next renders fails there too.

import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

import { todayUtc, utcCalendarDate } from './lastmod-date.mjs'

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const LANDING = 'apps/landing'
export const SNAPSHOT_PATH = `${LANDING}/src/generated/page-lastmod.json`
const DOCS_CONTENT_DIR = `${LANDING}/content/docs`
const FRAMEWORKS_MODULE = `${LANDING}/src/lib/frameworks.tsx`
const AGENTS_MODULE = `${LANDING}/src/lib/agent-setup/config.ts`

// What "the sources of a page" means: the route's own files plus the shared
// modules whose change alters what the page SAYS (its copy, code samples, FAQ,
// structured data). Global chrome (layout.tsx, Navbar, Footer, globals.css),
// styling primitives (components/ui) and analytics wiring are left out on
// purpose: they render on every page, so counting them would re-date all ~95
// URLs at once, which is exactly the signal the old build-time date sent.
// Repo-relative paths; a directory covers everything under it.
const MARKETING_SECTIONS = [
    `${LANDING}/src/components/HomepageHero`,
    `${LANDING}/src/components/FrameworkSnippets`,
    `${LANDING}/src/components/FrameworkStrip`,
    `${LANDING}/src/components/HomepageFeatures`,
    `${LANDING}/src/components/FeatureShowcase`,
    `${LANDING}/src/components/StackBlitzDemoSection`,
    `${LANDING}/src/components/FeedbackSection`,
    `${LANDING}/src/components/FAQSection`,
    `${LANDING}/src/components/StructuredData`,
    `${LANDING}/src/lib/faqs.ts`,
    `${LANDING}/src/lib/frameworks.tsx`,
    `${LANDING}/src/lib/community-links.ts`,
]

/**
 * Route template -> sources. `[framework]` and `[agent]` expand to one URL per
 * id (sitemap.ts maps FRAMEWORK_IDS and AGENT_IDS the same way); every page of
 * a template shares its sources, so they share a date.
 */
export const PAGE_SOURCES = {
    '/': [`${LANDING}/src/app/page.tsx`, ...MARKETING_SECTIONS],
    '/[framework]': [
        `${LANDING}/src/app/[framework]`,
        `${LANDING}/src/components/FrameworkGuide`,
        ...MARKETING_SECTIONS,
    ],
    '/support': [
        `${LANDING}/src/app/support`,
        `${LANDING}/src/lib/community-links.ts`,
    ],
    '/privacy': [`${LANDING}/src/app/privacy`],
    // The index page only: src/app/agent-setup also holds the per-agent route
    // and the prompt.md text route, which are not this page.
    '/agent-setup': [
        `${LANDING}/src/app/agent-setup/page.tsx`,
        `${LANDING}/src/lib/agent-setup/config.ts`,
        `${LANDING}/src/components/AgentIcon.tsx`,
        `${LANDING}/src/components/AgentSetupPill.tsx`,
    ],
    '/agent-setup/[agent]': [
        `${LANDING}/src/app/agent-setup/[agent]`,
        `${LANDING}/src/lib/agent-setup/config.ts`,
        `${LANDING}/src/lib/agent-setup/prompt.ts`,
        `${LANDING}/src/components/AgentIcon.tsx`,
        `${LANDING}/src/components/AgentSetupPill.tsx`,
    ],
}

// Docs pages depend on their own .mdx file, plus the per-framework snippet
// files any <FrameworkTabs topic="..."> embed reads from
// content/docs/_snippets/<topic>/. The /docs index also renders the DocsHome
// card grid.
const DOCS_INDEX_EXTRA_SOURCES = [`${LANDING}/src/components/docs/DocsHome.tsx`]

function posix(p) {
    return p.split(sep).join('/')
}

function git(args, root = REPO_ROOT) {
    return execFileSync('git', args, {
        cwd: root,
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
    }).trim()
}

/** Codepoint order: locale-independent, so the snapshot is byte-stable everywhere. */
function byCodepoint(a, b) {
    return a < b ? -1 : a > b ? 1 : 0
}

/**
 * The framework ids in sitemap order, read from FRAMEWORK_LIST in
 * apps/landing/src/lib/frameworks.tsx (`FRAMEWORKS.react, FRAMEWORKS.vue, …`).
 */
export function frameworkIdsFrom(source) {
    const list = source.match(
        /export const FRAMEWORK_LIST\b[^=]*=\s*\[([\s\S]*?)\]/,
    )
    const ids = list
        ? [...list[1].matchAll(/FRAMEWORKS\.([A-Za-z0-9_-]+)/g)].map(m => m[1])
        : []
    if (ids.length === 0) {
        throw new Error(
            `page-lastmod: no FRAMEWORK_LIST entries found in ${FRAMEWORKS_MODULE}; update frameworkIdsFrom() to its new shape.`,
        )
    }
    return ids
}

/**
 * The agent ids, read from the AGENTS array in
 * apps/landing/src/lib/agent-setup/config.ts. The array ends at the first line
 * that is exactly `]` (an entry's own values may contain brackets).
 */
export function agentIdsFrom(source) {
    const list = source.match(/export const AGENTS\b[^=]*=\s*\[([\s\S]*?)\n\]/)
    const ids = list
        ? [...list[1].matchAll(/\bid:\s*'([^']+)'/g)].map(m => m[1])
        : []
    if (ids.length === 0) {
        throw new Error(
            `page-lastmod: no AGENTS entries found in ${AGENTS_MODULE}; update agentIdsFrom() to its new shape.`,
        )
    }
    return ids
}

/**
 * The URL path of a docs file, given its path under content/docs without the
 * .mdx extension. An index file is served at its folder's URL, the same rule
 * fumadocs and lib/docs/llms.ts apply: `index` is /docs, `guides/index` is
 * /docs/guides.
 */
export function docsRouteFor(relWithoutExt) {
    const trimmed =
        relWithoutExt === 'index' ? '' : relWithoutExt.replace(/\/index$/, '')
    return trimmed === '' ? '/docs' : `/docs/${trimmed}`
}

/** Every `<FrameworkTabs topic="…">` topic an MDX page embeds. */
export function frameworkTabsTopicsIn(mdx) {
    return [
        ...new Set(
            [...mdx.matchAll(/<FrameworkTabs\b[^>]*\btopic="([^"]+)"/g)].map(
                m => m[1],
            ),
        ),
    ]
}

function walkMdx(dir, out = []) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name)
        if (entry.isDirectory()) walkMdx(full, out)
        else if (entry.isFile() && entry.name.endsWith('.mdx')) out.push(full)
    }
    return out
}

/** Sitemapped route path (no trailing slash) -> repo-relative sources. */
export function discoverPages(root = REPO_ROOT) {
    const read = rel => readFileSync(join(root, rel), 'utf8')
    const expansions = {
        '[framework]': frameworkIdsFrom(read(FRAMEWORKS_MODULE)),
        '[agent]': agentIdsFrom(read(AGENTS_MODULE)),
    }
    const pages = new Map()

    for (const [template, sources] of Object.entries(PAGE_SOURCES)) {
        const param = Object.keys(expansions).find(key =>
            template.includes(key),
        )
        if (!param) {
            pages.set(template, [...sources])
            continue
        }
        for (const id of expansions[param]) {
            pages.set(template.replace(param, id), [...sources])
        }
    }

    const docsRoot = join(root, DOCS_CONTENT_DIR)
    for (const file of walkMdx(docsRoot)) {
        const rel = posix(relative(docsRoot, file)).slice(0, -'.mdx'.length)
        const route = docsRouteFor(rel)
        const sources = [posix(relative(root, file))]
        for (const topic of frameworkTabsTopicsIn(readFileSync(file, 'utf8'))) {
            sources.push(`${DOCS_CONTENT_DIR}/_snippets/${topic}`)
        }
        if (route === '/docs') sources.push(...DOCS_INDEX_EXTRA_SOURCES)
        pages.set(route, sources)
    }

    return pages
}

/** Every mapped source that does not exist on disk: the map has rotted. */
function missingSources(pages, root) {
    const missing = new Set()
    for (const sources of pages.values()) {
        for (const p of sources) if (!existsSync(join(root, p))) missing.add(p)
    }
    return [...missing].toSorted(byCodepoint)
}

/**
 * Repo-relative paths `git status` reports as modified, staged, deleted,
 * renamed (both sides) or untracked. Parsed from `--porcelain -z`, where a
 * rename/copy entry is followed by a separate token holding its source path.
 */
export function parsePorcelainZ(output) {
    const tokens = output.split('\0').filter(Boolean)
    const paths = []
    for (let i = 0; i < tokens.length; i += 1) {
        const status = tokens[i].slice(0, 2)
        paths.push(tokens[i].slice(3))
        if (/[RC]/.test(status)) {
            i += 1
            if (i < tokens.length) paths.push(tokens[i])
        }
    }
    return paths
}

/** True when any dirty path is one of `sources` or lies under one of them. */
export function touchesSources(dirtyPaths, sources) {
    return dirtyPaths.some(path =>
        sources.some(src => path === src || path.startsWith(`${src}/`)),
    )
}

const COMMIT_MARK = '@@commit '
const NO_BLOB = /^0+$/

/** Repo-relative path -> blob id at HEAD, from `git ls-tree -r HEAD`. */
export function parseLsTree(output) {
    const blobs = new Map()
    for (const line of output.split('\n')) {
        const tab = line.indexOf('\t')
        if (tab === -1) continue
        const [, type, blob] = line.slice(0, tab).split(' ')
        if (type === 'blob') blobs.set(line.slice(tab + 1), blob)
    }
    return blobs
}

/**
 * File path -> UTC date of the newest commit that produced the file's CURRENT
 * content (its HEAD blob), or for a file gone from HEAD, the newest commit
 * that deleted it. Read from ONE `git log --raw` walk over every source at
 * once, because a `git log -1 -- <sources>` per page costs seconds per call on
 * Windows, which a pre-commit hook cannot afford ~95 times.
 *
 * Matching the HEAD blob is what makes the walk agree with `git log -1 --
 * <path>`: a union walk also visits side branches whose edit to this file a
 * merge later dropped (that commit's blob is not HEAD's, so it is skipped),
 * and dense-combined merge diffs list a file only when the merge result
 * differs from EVERY parent, i.e. the merge itself authored the content, the
 * same merges `git log -1 -- path` reports. `%cI` carries the committer's
 * offset and utcCalendarDate normalises it; never `%cs`, which prints the
 * committer's LOCAL date.
 */
export function parseRawLog(output, headBlobs) {
    const current = new Map()
    const anyEntry = new Map()
    const producingDates = new Map()
    let date = null
    const keepNewest = (map, path) => {
        const seen = map.get(path)
        if (seen === undefined || date > seen) map.set(path, date)
    }
    for (const line of output.split('\n')) {
        if (line.startsWith(COMMIT_MARK)) {
            date = utcCalendarDate(line.slice(COMMIT_MARK.length))
            continue
        }
        if (date === null || !line.startsWith(':')) continue
        const tab = line.indexOf('\t')
        if (tab === -1) continue
        const path = line.slice(tab + 1)
        const colons = line.match(/^:+/)[0].length
        const fields = line.slice(colons, tab).split(' ')
        // `colons` parents -> colons+1 modes, then colons+1 blob ids; the last
        // blob id is the commit's resulting content (all zeros = deleted).
        const resultBlob = fields[2 * (colons + 1) - 1]
        keepNewest(anyEntry, path)
        const head = headBlobs.get(path)
        if (
            head === undefined ? NO_BLOB.test(resultBlob) : resultBlob === head
        ) {
            keepNewest(current, path)
            if (!producingDates.has(path)) producingDates.set(path, new Set())
            producingDates.get(path).add(date)
        }
    }
    // A HEAD blob with no producing commit in reach only happens past a
    // shallow boundary; fall back to the file's newest entry of any kind.
    for (const [path, newest] of anyEntry) {
        if (!current.has(path)) current.set(path, newest)
    }
    // The same content produced on different days (a branch that changed a
    // file and reverted it, merged with the line that never changed it) is
    // where git's per-path history simplification and "newest producer"
    // disagree; the caller asks git for exactly those files.
    const ambiguous = [...producingDates]
        .filter(([, dates]) => dates.size > 1)
        .map(([path]) => path)
        .toSorted(byCodepoint)
    return { fileDates: current, ambiguous }
}

/** Newest date among the files that are, or lie under, one of `sources`. */
export function newestDateFor(sources, fileDates) {
    let newest = null
    for (const [path, date] of fileDates) {
        if (!touchesSources([path], sources)) continue
        if (newest === null || date > newest) newest = date
    }
    return newest
}

/**
 * Route -> UTC YYYY-MM-DD of the last commit that touched any of its sources,
 * or today when one of them is dirty/untracked (the pending commit is the
 * modification).
 */
function datePages(pages, root = REPO_ROOT, now = new Date()) {
    const today = todayUtc(now)
    const statusOutput = execFileSync(
        'git',
        ['status', '--porcelain=v1', '-z', '--untracked-files=all'],
        { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
    )
    const dirty = parsePorcelainZ(statusOutput)
    const allSources = [...new Set([...pages.values()].flat())].toSorted(
        byCodepoint,
    )
    const headBlobs = parseLsTree(
        git(
            [
                '-c',
                'core.quotePath=false',
                'ls-tree',
                '-r',
                'HEAD',
                '--',
                ...allSources,
            ],
            root,
        ),
    )
    const { fileDates, ambiguous } = parseRawLog(
        git(
            [
                '-c',
                'core.quotePath=false',
                'log',
                '--raw',
                '--no-abbrev',
                '--no-renames',
                '--diff-merges=dense-combined',
                `--format=${COMMIT_MARK}%cI`,
                '--',
                ...allSources,
            ],
            root,
        ),
        headBlobs,
    )
    for (const path of ambiguous) {
        const committedAt = git(['log', '-1', '--format=%cI', '--', path], root)
        if (committedAt !== '')
            fileDates.set(path, utcCalendarDate(committedAt))
    }
    const dated = {}
    for (const route of [...pages.keys()].toSorted(byCodepoint)) {
        const sources = pages.get(route)
        dated[route] = touchesSources(dirty, sources)
            ? today
            : (newestDateFor(sources, fileDates) ?? today)
    }
    return dated
}

function serialize(snapshot) {
    // 4-space indent = the repo's prettier config, so lint-staged's
    // `prettier --check` on *.json accepts the file as written.
    return `${JSON.stringify(snapshot, null, 4)}\n`
}

function generate(root = REPO_ROOT) {
    const pages = discoverPages(root)
    const missing = missingSources(pages, root)
    if (missing.length > 0) {
        throw new Error(
            `page-lastmod: PAGE_SOURCES names paths that no longer exist — update scripts/seo/page-lastmod.mjs:\n  ${missing.join('\n  ')}`,
        )
    }
    return { pages: datePages(pages, root) }
}

function isCalendarDate(value) {
    return (
        typeof value === 'string' &&
        /^\d{4}-\d{2}-\d{2}$/.test(value) &&
        !Number.isNaN(Date.parse(`${value}T00:00:00Z`)) &&
        // Date.parse rolls 2026-02-30 over to March; a real date round-trips.
        utcCalendarDate(`${value}T00:00:00Z`) === value
    )
}

/**
 * Every reason the committed snapshot cannot be trusted. `expected` is the
 * sitemapped route list; `fresh` (route -> date from git now) is passed only
 * when the checkout has history, and enables the staleness comparison.
 */
export function snapshotProblems({ committed, expected, today, fresh }) {
    const problems = []
    const expectedSet = new Set(expected)
    for (const key of expected) {
        if (!(key in committed)) problems.push(`missing entry for ${key}`)
    }
    for (const key of Object.keys(committed).toSorted(byCodepoint)) {
        if (!expectedSet.has(key))
            problems.push(`orphaned entry ${key} (no such page)`)
    }
    for (const [key, value] of Object.entries(committed)) {
        if (!isCalendarDate(value)) {
            problems.push(
                `${key}: ${JSON.stringify(value)} is not a YYYY-MM-DD date`,
            )
        } else if (value > today) {
            problems.push(`${key}: ${value} is in the future`)
        }
    }
    if (fresh) {
        const DAY_MS = 24 * 60 * 60 * 1000
        for (const key of expected) {
            const have = committed[key]
            const want = fresh[key]
            if (!isCalendarDate(have) || !isCalendarDate(want)) continue
            const lag =
                (Date.parse(`${want}T00:00:00Z`) -
                    Date.parse(`${have}T00:00:00Z`)) /
                DAY_MS
            if (lag > 1) {
                problems.push(
                    `${key}: snapshot says ${have}, git says ${want} — run \`pnpm run seo:lastmod\``,
                )
            }
        }
    }
    return problems
}

function check(root = REPO_ROOT) {
    const snapshotFile = join(root, SNAPSHOT_PATH)
    if (!existsSync(snapshotFile)) {
        console.error(
            `::error::page-lastmod: ${SNAPSHOT_PATH} is missing — run \`pnpm run seo:lastmod\`.`,
        )
        return 1
    }
    const committed = JSON.parse(readFileSync(snapshotFile, 'utf8')).pages ?? {}
    const pages = discoverPages(root)
    const expected = [...pages.keys()].toSorted(byCodepoint)
    const missing = missingSources(pages, root)
    const shallow =
        git(['rev-parse', '--is-shallow-repository'], root) === 'true'
    const problems = [
        ...missing.map(p => `PAGE_SOURCES names ${p}, which does not exist`),
        ...snapshotProblems({
            committed,
            expected,
            today: todayUtc(),
            fresh:
                shallow || missing.length > 0
                    ? undefined
                    : datePages(pages, root),
        }),
    ]

    if (problems.length > 0) {
        console.error('::error::page-lastmod snapshot is stale or malformed:')
        for (const p of problems) console.error(`  - ${p}`)
        return 1
    }
    console.log(
        `OK: page-lastmod snapshot covers all ${expected.length} sitemapped pages${
            shallow
                ? ' (shallow clone: coverage and date sanity only; the freshness comparison needs history)'
                : ' and is within a day of git'
        }.`,
    )
    return 0
}

function main() {
    if (process.argv.includes('--check')) {
        process.exit(check())
    }
    const snapshot = generate()
    writeFileSync(join(REPO_ROOT, SNAPSHOT_PATH), serialize(snapshot))
    console.log(
        `page-lastmod: wrote ${Object.keys(snapshot.pages).length} entries to ${SNAPSHOT_PATH}`,
    )
}

if (
    import.meta.url === `file://${process.argv[1]}` ||
    process.argv[1] === fileURLToPath(import.meta.url)
) {
    main()
}
