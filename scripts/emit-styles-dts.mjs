// Emits dist/styles.d.ts for a framework package's `./styles` subpath export.
//
// The subpath's runtime target is dist/tailwind-prefixed.css and must stay that
// way. TypeScript 6 started type-checking side-effect imports, so without a
// `types` condition backed by a real declaration file the documented
// `import '@upupjs/react/styles'` fails with TS2882 (issue #357). An empty
// module declaration is all TS needs to resolve the specifier; it contributes no
// types and no runtime.
//
// Run from a package directory (cwd = packages/<name>) as the last step of that
// package's build, after the JS build has finished writing/cleaning dist.
import { mkdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const distDir = resolve(process.cwd(), process.argv[2] ?? 'dist')
const target = join(distDir, 'styles.d.ts')

const contents = `// Generated by scripts/emit-styles-dts.mjs — do not edit.
// Declares the './styles' subpath (runtime target: ./tailwind-prefixed.css) so
// TypeScript 6+ can resolve \`import '@upupjs/<framework>/styles'\`.
export {}
`

mkdirSync(distDir, { recursive: true })
writeFileSync(target, contents)
console.log(`[emit-styles-dts] wrote ${target}`)
